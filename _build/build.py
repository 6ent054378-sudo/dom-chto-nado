def flexpat(text):
    """Паттерн, устойчивый к переносам строк, отступам и <br>."""
    t = re.sub(r"(?i)<br\s*/?>", " ", text)
    words = t.split()
    return r"(?:\s|<br\s*/?>)+".join(re.escape(w) for w in words)


def reinsert_br(matched, new):
    """Восстанавливает позиции <br> из совпадения в новом тексте."""
    if "<br" in new.lower():
        return new
    parts = re.split(r"(?i)<br\s*/?>", matched)
    idxs, cnt = [], 0
    for i, p in enumerate(parts):
        if i > 0:
            idxs.append(cnt)
        cnt += len(p.split())
    if not idxs:
        return new
    out = new.split()
    for pos in sorted(idxs, reverse=True):
        if 0 < pos < len(out):
            out.insert(pos, "<br>")
    return " ".join(out)


def rep(c, old, new, label=""):
    """Замена текста, нечувствительная к переносам строк, отступам и <br>."""
    c2, n = re.subn(flexpat(old), lambda m: reinsert_br(m.group(0), new), c)
    if n == 0:
        LOG.append(("MISS", label or old[:70]))
    elif n > 1:
        LOG.append(("MULTI x%d" % n, label or old[:70]))
    return c2


def rep_all(c, old, new, label=""):
    """Замена всех вхождений."""
    c2, n = re.subn(flexpat(old), lambda m: reinsert_br(m.group(0), new), c)
    if n == 0:
        LOG.append(("MISS", label or old[:70]))
    return c2


