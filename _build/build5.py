import re, glob, os

SEC = "/tmp/work/sec"
LOG = []


def flexpat(text):
    t = re.sub(r"(?i)<br\s*/?>", " ", text)
    words = t.split()
    return r"(?:\s|<br\s*/?>)+".join(re.escape(w) for w in words)


def rep(c, old, new, label="", expect=None):
    c2, n = re.subn(flexpat(old), lambda m: new, c)
    if expect is not None and n != expect:
        LOG.append((f"n={n} (ожидалось {expect})", label or old[:60]))
    elif n == 0:
        LOG.append(("MISS", label or old[:60]))
    return c2


